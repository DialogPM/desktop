// Builds crates/voice-fx to WebAssembly and embeds it in src/lib/voiceFxWasm.gen.ts (base64):
// the app's CSP does not allow fetching it, and the bundler does not inline .wasm files.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

execFileSync("cargo", ["build", "-q", "-p", "voice-fx", "--release", "--target", "wasm32-unknown-unknown"], { stdio: "inherit" });
// Cargo's output directory: CARGO_TARGET_DIR (relative to the workspace root) or `target/`.
const root = fileURLToPath(new URL("../..", import.meta.url));
const targetDir = resolve(root, process.env.CARGO_TARGET_DIR || "target");
const wasm = readFileSync(resolve(targetDir, "wasm32-unknown-unknown/release/voice_fx.wasm"));
const out = `// GENERATED by scripts/build-voice-fx.mjs from crates/voice-fx. Do not edit.\nexport const VOICE_FX_WASM = "${wasm.toString("base64")}";\n`;
writeFileSync(new URL("../src/lib/voiceFxWasm.gen.ts", import.meta.url), out);
